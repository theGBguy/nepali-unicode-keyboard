#!/usr/bin/env python3
"""Writes iosApp/App/ThemeSwatches.swift from the shared KeyboardTheme.kt palettes.

The iOS app target doesn't link the shared Kotlin framework (only the keyboard extension does),
so the Settings theme picker needs its own copy of the swatch colours. Run after changing a
palette:  python3 tools/themes/make_swift.py   (or --check to fail when the copy is stale).
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
KOTLIN = ROOT / "shared/src/commonMain/kotlin/io/github/thegbguy/nepalikeyboard/ui/keyboard/KeyboardTheme.kt"
SWIFT = ROOT / "iosApp/App/ThemeSwatches.swift"
FIELDS = ["background", "key", "functionKey", "keyText", "accent"]


def camel(name: str) -> str:
    head, *rest = name.lower().split("_")
    return head + "".join(part.title() for part in rest)


def main() -> int:
    source = KOTLIN.read_text()
    match = re.search(r"enum class KeyboardTheme \{\s*([A-Z_,\s]+);", source)
    if match is None:
        sys.exit(f"KeyboardTheme enum not found in {KOTLIN}")
    themes = [t.strip() for t in match.group(1).split(",") if t.strip()]
    palettes = {}
    for name, body in re.findall(r"val (\w+) = ThemePalette\((.*?)\n    \)", source, re.S):
        values = dict(re.findall(r"(\w+) = (0x[0-9A-Fa-f]{8}|true|false)", body))
        palettes[name] = values

    lines = [
        "import SwiftUI",
        "",
        "// Generated by tools/themes/make_swift.py from shared KeyboardTheme.kt. Don't edit by hand.",
        "",
        "/** The keyboard themes as the app's Settings shows them; stored by `rawValue` in the App Group. */",
        "enum KeyboardThemeChoice: String, CaseIterable, Identifiable {",
    ]
    lines += [f'    case {camel(t)} = "{t}"' for t in themes]
    lines += ["", "    var id: String { rawValue }", "", "    /** Swatch colours; System shows the light or dark palette. */",
              "    func swatch(dark: Bool) -> ThemeSwatch {", "        switch self {"]
    for t in themes:
        if t == "SYSTEM":
            lines.append("        case .system: return dark ? Self.dark.swatch(dark: true) : Self.light.swatch(dark: false)")
            continue
        p = palettes[t]
        args = ", ".join(f"{f}: 0x{p[f][4:]}" for f in FIELDS)
        lines.append(f"        case .{camel(t)}: return ThemeSwatch({args})")
    lines += ["        }", "    }", "}", "", "struct ThemeSwatch {"]
    lines += [f"    let {f}: UInt32" for f in FIELDS]
    lines += ["}", ""]
    text = "\n".join(lines)

    if "--check" in sys.argv:
        if not SWIFT.exists() or SWIFT.read_text() != text:
            print(f"{SWIFT.relative_to(ROOT)} is stale: run tools/themes/make_swift.py")
            return 1
        return 0
    SWIFT.write_text(text)
    print(f"wrote {SWIFT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
