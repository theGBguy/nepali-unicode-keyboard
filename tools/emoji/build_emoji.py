#!/usr/bin/env python3
"""Builds app/src/main/assets/emoji.tsv from Unicode's emoji-test.txt (Unicode 15.1).

Keeps fully-qualified emoji without skin-tone or hair variants, merges "Smileys & Emotion"
and "People & Body", drops "Component". Output: one line per category, emoji separated by
spaces. The app hides emoji the phone's font can't draw (Paint.hasGlyph).

    python3 tools/emoji/build_emoji.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "emoji-test.txt")
OUT = os.path.join(HERE, "..", "..", "app", "src", "main", "assets", "emoji.tsv")

CATEGORY = {
    "Smileys & Emotion": "smileys",
    "People & Body": "smileys",
    "Animals & Nature": "animals",
    "Food & Drink": "food",
    "Activities": "activities",
    "Travel & Places": "travel",
    "Objects": "objects",
    "Symbols": "symbols",
    "Flags": "flags",
}
ORDER = ["smileys", "animals", "food", "activities", "travel", "objects", "symbols", "flags"]
VARIANTS = {0x1F3FB, 0x1F3FC, 0x1F3FD, 0x1F3FE, 0x1F3FF, 0x1F9B0, 0x1F9B1, 0x1F9B2, 0x1F9B3}

out = {c: [] for c in ORDER}
group = None
for line in open(SRC, encoding="utf-8"):
    m = re.match(r"# group: (.+)", line)
    if m:
        group = CATEGORY.get(m.group(1).strip())
        continue
    if not group or line.startswith("#") or "; fully-qualified" not in line:
        continue
    codes = [int(c, 16) for c in line.split(";")[0].split()]
    if any(c in VARIANTS for c in codes):
        continue
    out[group].append("".join(map(chr, codes)))

with open(OUT, "w", encoding="utf-8") as f:
    f.write("# Generated by tools/emoji/build_emoji.py from Unicode emoji-test.txt 15.1 (Unicode License v3)\n")
    for c in ORDER:
        f.write(c + "\t" + " ".join(out[c]) + "\n")
print({c: len(v) for c, v in out.items()}, sum(map(len, out.values())))
