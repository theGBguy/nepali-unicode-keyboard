#!/usr/bin/env python3
"""Builds app/src/main/assets/emoji_keywords.tsv: search words for each emoji in emoji.tsv.

Words come from Unicode CLDR's emoji annotations (names and keywords) in English and Nepali,
plus the derived annotations for flags and keycaps. Run build_emoji.py first.

    python3 tools/emoji/build_emoji_keywords.py

Output: one line per emoji, `emoji<TAB>english words<TAB>nepali words`, words lowercased,
de-duplicated and separated by spaces, in the emoji panel's order. Multi-word keywords are
split into words; a search matches when every word typed starts one of the emoji's words.
"""
import json
import os
import re
import urllib.request

CLDR = "49.0.0"
BASE = f"https://raw.githubusercontent.com/unicode-org/cldr-json/{CLDR}/cldr-json"
HERE = os.path.dirname(os.path.abspath(__file__))
ASSETS = os.path.join(HERE, "..", "..", "app", "src", "main", "assets")
CACHE = os.path.join(HERE, "cldr-cache")  # git-ignored download cache


def fetch(kind, lang):
    os.makedirs(CACHE, exist_ok=True)
    path = os.path.join(CACHE, f"{kind}-{lang}-{CLDR}.json")
    if not os.path.exists(path):
        folder = "cldr-annotations-full/annotations" if kind == "annotations" else \
            "cldr-annotations-derived-full/annotationsDerived"
        urllib.request.urlretrieve(f"{BASE}/{folder}/{lang}/annotations.json", path)
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    return data["annotations" if kind == "annotations" else "annotationsDerived"]["annotations"]


def words(entry):
    out = []
    for phrase in entry.get("tts", []) + entry.get("default", []):
        for w in re.split(r"[\s:,“”\"()]+", phrase.lower()):
            w = w.strip(".'’\u200c\u200d")
            if w and w not in out:
                out.append(w)
    return out


def annotations(lang):
    merged = dict(fetch("derived", lang))
    merged.update(fetch("annotations", lang))
    return {key.replace("\ufe0f", ""): value for key, value in merged.items()}


emoji = []
with open(os.path.join(ASSETS, "emoji.tsv"), encoding="utf-8") as f:
    for line in f:
        if line.startswith("#") or "\t" not in line:
            continue
        emoji += [e for e in line.rstrip("\n").split("\t", 1)[1].split(" ") if e]

en, ne = annotations("en"), annotations("ne")
missing = 0
with open(os.path.join(ASSETS, "emoji_keywords.tsv"), "w", encoding="utf-8") as f:
    f.write(f"# Generated by tools/emoji/build_emoji_keywords.py from Unicode CLDR {CLDR} emoji annotations (Unicode License v3)\n")
    for e in emoji:
        key = e.replace("\ufe0f", "")
        en_words, ne_words = words(en.get(key, {})), words(ne.get(key, {}))
        if not en_words and not ne_words:
            missing += 1
            continue
        f.write(f"{e}\t{' '.join(en_words)}\t{' '.join(ne_words)}\n")
print(len(emoji), "emoji,", missing, "without words")
