    fun monthLength(year: Int, month: Int): Int? {
        if (year !in FIRST_YEAR..LAST_YEAR || month !in 1..12) return null
        return MONTH_DAYS[(year - FIRST_YEAR) * 12 + month - 1]
    }

    /** The BS date of [epochDay], or null outside the table. */
    fun toBs(epochDay: Long): BsDate? {
        var rest = epochDay - ANCHOR
        if (rest < 0) return null
        for (i in MONTH_DAYS.indices) {
            val length = MONTH_DAYS[i]
            if (rest < length) return BsDate(FIRST_YEAR + i / 12, i % 12 + 1, rest.toInt() + 1)
            rest -= length
        }
        return null
    }

    /** The epoch day of a BS date, or null if it isn't a real date in the table. */
    fun toEpochDay(date: BsDate): Long? {
        val length = monthLength(date.year, date.month) ?: return null
        if (date.day !in 1..length) return null
        var days = 0L
        val index = (date.year - FIRST_YEAR) * 12 + date.month - 1
        for (i in 0 until index) days += MONTH_DAYS[i]
        return ANCHOR + days + date.day - 1
    }
